/* Local dictionary lookup — only for Tigrinya ↔ English pairs */
function _transLookupLocal(text) {
  const from = _transFromLang();
  const to   = _transToLang();
  if (!((from === 'en' && to === 'ti') || (from === 'ti' && to === 'en'))) return [];
  const q = text.toLowerCase().trim();
  const results = [];
  if (from === 'en') {
    for (const d of DICT) {
      if (!d.tig || !d.eng) continue;
      const variants = d.eng.toLowerCase().split('/').map(s => s.trim());
      if (variants.some(v => v === q))
        results.push({ tig: d.tig, rom: d.rom, eng: d.eng, emoji: d.emoji || '', exact: true });
    }
    if (!results.length) {
      for (const d of DICT) {
        if (!d.tig || !d.eng) continue;
        if (d.eng.toLowerCase().includes(q) || (d.rom && d.rom.toLowerCase() === q))
          results.push({ tig: d.tig, rom: d.rom, eng: d.eng, emoji: d.emoji || '', exact: false });
      }
    }
  } else {
    for (const d of DICT) {
      if (!d.tig || !d.eng) continue;
      if (d.tig === text || (d.rom && d.rom.toLowerCase() === q))
        results.push({ tig: d.tig, rom: d.rom, eng: d.eng, emoji: d.emoji || '', exact: true });
    }
    if (!results.length) {
      for (const d of DICT) {
        if (!d.tig || !d.eng) continue;
        if (d.tig.includes(text) || (d.rom && d.rom.toLowerCase().includes(q)))
          results.push({ tig: d.tig, rom: d.rom, eng: d.eng, emoji: d.emoji || '', exact: false });
      }
    }
  }
  return results.slice(0, 4);
}

function _transShowLocal(results, outEl, statEl, copyBtn) {
  const showTig = _transFromLang() === 'en';
  outEl.innerHTML = '';
  results.forEach((r, i) => {
    const row = document.createElement('div');
    row.style.cssText = 'padding:10px 0;' + (i > 0 ? 'border-top:1px solid var(--border);' : '');
    if (r.emoji) {
      const em = document.createElement('span');
      em.style.cssText = 'font-size:1.2rem;margin-right:6px;vertical-align:middle;';
      em.textContent = r.emoji;
      row.appendChild(em);
    }
    const main = document.createElement('span');
    main.style.cssText = showTig
      ? 'font-family:"Noto Serif Ethiopic",serif;font-size:1.15rem;font-weight:700;'
      : 'font-size:1rem;font-weight:700;';
    main.textContent = showTig ? r.tig : r.eng;
    row.appendChild(main);
    if (showTig && r.rom) {
      const rm = document.createElement('div');
      rm.style.cssText = 'font-size:0.75rem;color:var(--text-dim);font-style:italic;margin-top:2px;';
      rm.textContent = r.rom;
      row.appendChild(rm);
    }
    if (results.length > 1) {
      const sub = document.createElement('div');
      sub.style.cssText = 'font-size:0.72rem;color:var(--text-dim);margin-top:1px;';
      sub.textContent = showTig ? r.eng : r.tig;
      row.appendChild(sub);
    }
    outEl.appendChild(row);
  });
  const firstResult = showTig ? results[0].tig : results[0].eng;
  statEl.style.color = 'var(--green)';
  statEl.textContent = results[0].exact ? '✓ Found in dictionary' : '✓ Best match from dictionary';
  const actEl = document.getElementById('transOutActions');
  if (actEl) actEl.style.display = '';
  copyBtn.onclick = () => navigator.clipboard?.writeText(firstResult)
    .then(() => hubToast('Copied!')).catch(() => {});
  window._lastTranslation = firstResult;
  window._lastTransLang = _transToLang();
}

async function _doTranslate() {
  const text    = document.getElementById('transInput').value.trim();
  const outEl   = document.getElementById('transOutput');
  const statEl  = document.getElementById('transStatus');
  const btn     = document.getElementById('transBtn');
  const copyBtn = document.getElementById('transCopyBtn');
  const actEl   = document.getElementById('transOutActions');
  if (!text) {
    outEl.innerHTML = '<span class="trans-ph">Please enter some text first.</span>';
    if (actEl) actEl.style.display = 'none';
    return;
  }
  statEl.textContent = ''; statEl.style.color = '';
  if (actEl) actEl.style.display = 'none';

  const localHits = _transLookupLocal(text);
  if (localHits.length) { _transShowLocal(localHits, outEl, statEl, copyBtn); return; }

  const src = _transFromLang();
  const tgt = _transToLang();
  btn.disabled = true; btn.textContent = 'Translating…';
  outEl.innerHTML = '<span class="trans-ph">Translating…</span>';
  try {
    const res  = await fetch('https://api.mymemory.translated.net/get?q=' + encodeURIComponent(text) + '&langpair=' + src + '|' + tgt);
    const data = await res.json();
    if (data.responseStatus === 200 && data.responseData?.translatedText) {
      const tmp = document.createElement('textarea');
      tmp.innerHTML = data.responseData.translatedText;
      const translation = tmp.value;
      window._lastTranslation = translation;
      window._lastTransLang = tgt;
      outEl.innerHTML = '';
      const p = document.createElement('p');
      p.style.cssText = _ETHIOPIC.has(tgt)
        ? 'font-family:"Noto Serif Ethiopic",serif;font-size:1.1rem;line-height:1.9;'
        : _RTL.has(tgt) ? 'font-size:0.95rem;line-height:1.7;direction:rtl;text-align:right;'
        : 'font-size:0.95rem;line-height:1.7;';
      p.textContent = translation;
      outEl.appendChild(p);
      statEl.style.color = 'var(--text-dim)';
      statEl.textContent = (src === 'ti' || tgt === 'ti')
        ? '⚠ Machine translation — may be inaccurate for Tigrinya'
        : '✓ Translated';
      if (actEl) actEl.style.display = '';
      copyBtn.onclick = () => navigator.clipboard?.writeText(translation)
        .then(() => hubToast('Copied!')).catch(() => {});
    } else if (data.responseStatus === 429) {
      outEl.innerHTML = '<span class="trans-ph" style="color:var(--red)">Rate limit reached — please wait a moment and try again.</span>';
    } else {
      outEl.innerHTML = '<span class="trans-ph" style="color:var(--red)">Translation not available. Try a shorter phrase.</span>';
    }
  } catch {
    outEl.innerHTML = '<span class="trans-ph" style="color:var(--red)">Network error. Check your connection.</span>';
  } finally {
    btn.disabled = false; btn.textContent = 'Translate →';
  }
}
document.getElementById('transBtn').addEventListener('click', _doTranslate);

