let libCat = 'all', libQuery = '';
const LIB_GRAD = { language:'linear-gradient(135deg,#0ea5e9,#0369a1)', children:'linear-gradient(135deg,#a855f7,#7c3aed)', history:'linear-gradient(135deg,#f59e0b,#b45309)', culture:'linear-gradient(135deg,#ec4899,#be185d)', stories:'linear-gradient(135deg,#f97316,#c2410c)', textbook:'linear-gradient(135deg,#3B82F6,#16a34a)' };
const LIB_COL  = { language:'#0ea5e9', children:'#a855f7', history:'#f59e0b', culture:'#ec4899', stories:'#f97316', textbook:'#3B82F6' };
function _hlLib(t, q) { if(!q)return t; const i=t.toLowerCase().indexOf(q); if(i<0)return t; return t.slice(0,i)+'<mark class="lib-hl">'+t.slice(i,i+q.length)+'</mark>'+t.slice(i+q.length); }

function getTbDone(bookId) {
  const all = JSON.parse(localStorage.getItem('hub-tb-done') || '{}');
  return all[bookId] || [];
}
function markChapterDone(bookId, chIdx) {
  const all = JSON.parse(localStorage.getItem('hub-tb-done') || '{}');
  if (!all[bookId]) all[bookId] = [];
  if (!all[bookId].includes(chIdx)) all[bookId].push(chIdx);
  localStorage.setItem('hub-tb-done', JSON.stringify(all));
}
function isBookLocked(book) {
  if (book.id === 19) {
    const g1 = BOOKS.find(b => b.id === 18);
    return g1 && getTbDone(18).length < g1.chapters.length;
  }
  return false;
}

function renderBooks() {
  const grid = document.getElementById('bookGrid');
  if (!grid) return;
  const items = BOOKS.filter(b =>
    (libCat === 'all' || b.cat === libCat) &&
    (libQuery === '' || b.title.toLowerCase().includes(libQuery) || b.author.toLowerCase().includes(libQuery))
  );
  if (!items.length) { grid.innerHTML = '<div class="lib-empty">No books found 📚</div>'; return; }
  grid.innerHTML = items.map(b => {
    const locked = isBookLocked(b);
    const progStr = b.cat === 'textbook' ? getTbDone(b.id).length + '/' + b.chapters.length + ' units done' : '';
    const grad = LIB_GRAD[b.cat] || LIB_GRAD.textbook;
    const col  = LIB_COL[b.cat]  || '#3B82F6';
    return '<div class="book-card' + (locked ? ' book-locked' : '') + '" style="border-left-color:' + col + '">' +
      '<div class="book-cover-wrap">' +
        '<div class="book-cover" style="background:' + grad + '">' + b.emoji + '</div>' +
        (locked ? '<div class="book-lock-over">🔒</div>' : '') +
      '</div>' +
      '<div class="book-info">' +
        '<div class="book-title">' + _hlLib(b.title, libQuery) + '</div>' +
        '<div class="book-author">by ' + _hlLib(b.author, libQuery) + '</div>' +
        '<div class="book-desc">' + b.desc + '</div>' +
        (progStr ? '<div class="tb-grade-prog">' + progStr + '</div>' : '') +
        '<div class="book-footer">' +
          '<span class="book-cat" style="color:' + col + ';background:' + col + '22;border:1px solid ' + col + '44">' + b.cat + '</span>' +
          (locked
            ? '<button class="book-read-btn btn-locked" disabled>🔒 Complete Grade 1 first</button>'
            : '<button class="book-read-btn" data-bid="' + b.id + '">Read →</button>') +
        '</div>' +
      '</div>' +
    '</div>';
  }).join('');
  grid.querySelectorAll('.book-card').forEach((card, i) => {
    card.classList.add('stagger-in'); card.style.animationDelay = (i * 0.04) + 's';
    card.addEventListener('click', () => {
      card.classList.remove('tapping'); void card.offsetWidth; card.classList.add('tapping');
      card.addEventListener('animationend', () => card.classList.remove('tapping'), { once: true });
    });
  });
  grid.querySelectorAll('.book-read-btn:not(.btn-locked)').forEach(btn =>
    btn.addEventListener('click', e => { e.stopPropagation(); openBook(+btn.dataset.bid); })
  );
}

function openBook(id) {
  const book = BOOKS.find(b => b.id === id);
  if (!book) return;
  document.getElementById('readerEmoji').textContent = book.emoji;
  document.getElementById('readerTitle').textContent = book.title;
  document.getElementById('readerAuthor').textContent = 'by ' + book.author;
  const doneChs = book.cat === 'textbook' ? getTbDone(book.id) : [];
  document.getElementById('readerBody').innerHTML = book.chapters.map((ch, i) => {
    const isDone = doneChs.includes(i);
    const doneBtn = book.cat === 'textbook'
      ? '<button class="tb-done-btn' + (isDone ? ' done' : '') + '" data-bid="' + book.id + '" data-chi="' + i + '">' +
          (isDone ? '✓ Unit Complete' : '✓ Mark Unit Complete') +
        '</button>' +
        '<div class="tb-done-hint">' + (isDone ? 'Completed!' : 'Tap when you finish this unit') + '</div>'
      : '';
    return '<div class="reader-ch"><h3>' + ch.title + '</h3>' + ch.body + doneBtn + '</div>';
  }).join('');
  const reader = document.getElementById('bookReader');
  reader.classList.add('open');
  reader.querySelector('.reader-body').scrollTop = 0;
  document.body.style.overflow = 'hidden';
  document.getElementById('readerBody').querySelectorAll('.tb-done-btn:not(.done)').forEach(btn => {
    btn.addEventListener('click', () => {
      const bid = +btn.dataset.bid, chi = +btn.dataset.chi;
      markChapterDone(bid, chi);
      btn.classList.add('done');
      btn.textContent = '✓ Unit Complete';
      const hint = btn.nextElementSibling;
      if (hint) hint.textContent = 'Completed!';
      const g1 = BOOKS.find(b => b.id === 18);
      if (bid === 18 && g1 && getTbDone(18).length === g1.chapters.length) {
        hubToast('🎉 Grade 1 complete! Grade 2 is now unlocked!');
        renderBooks();
      }
    });
  });
}

document.getElementById('readerClose').addEventListener('click', () => {
  document.getElementById('bookReader').classList.remove('open');
  document.body.style.overflow = '';
});

document.querySelectorAll('#libTabs .tab-btn').forEach(btn => {
  btn.addEventListener('click', () => {
    document.querySelectorAll('#libTabs .tab-btn').forEach(b => b.classList.remove('active'));
    btn.classList.add('active');
    libCat = btn.dataset.lcat;
    renderBooks();
  });
});

document.getElementById('libSearch').addEventListener('input', e => {
  libQuery = e.target.value.trim().toLowerCase();
  renderBooks();
});

